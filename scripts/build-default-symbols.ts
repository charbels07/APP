/**
 * Pictures of the app's built-in vocabulary (the words every board starts with).
 * For each word: the choice in pictograms/default-overrides.json, else the Mulberry symbol with
 * the same English name, else the OpenMoji drawing of the word's emoji, else the emoji itself.
 *
 *   npm run build:symbols     (after npm run build:picto)
 *
 * Output: assets/symbols/*.webp (256 px), src/data/symbolMap.ts, pictograms/database/defaults.csv.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { BUILTIN_CONCEPTS } from '../src/data/concepts.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.env.PICTO_SOURCES ?? join(root, '../picto-sources');
const out = join(root, 'assets/symbols');
const SIZE = 256;

const norm = (s: string) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const stripVs = (s: string) => s.replace(/️/g, '');
const overrides: Record<string, string | null> = JSON.parse(readFileSync(join(root, 'pictograms/default-overrides.json'), 'utf8'));

// The database built by build-pictograms.ts: key → original file.
const rows = readFileSync(join(root, 'pictograms/database/pictograms.csv'), 'utf8').replace(/^﻿/, '').split('\n').slice(1);
const fileOf = new Map<string, string>();
const mulberryByName = new Map<string, string>();
for (const line of rows) {
  const m = line.match(/^\d+,("(?:[^"]|"")*"|[^,]*),[^,]*,("(?:[^"]|"")*"|[^,]*),/);
  if (!m) continue;
  const un = (v: string) => (v.startsWith('"') ? v.slice(1, -1).replace(/""/g, '"') : v);
  const key = un(m[1]);
  fileOf.set(key, un(m[2]));
  if (key.startsWith('mulberry/')) {
    // "teacher_1a", "breakfast_1" are variants of "teacher", "breakfast": the first one stands for the word.
    const name = norm(key.slice(9).replace(/_,_to$/, '').replace(/_\d+[a-z]?$/, ''));
    if (!mulberryByName.has(name)) mulberryByName.set(name, key);
  }
}
const openmoji: { emoji: string; hexcode: string }[] = JSON.parse(readFileSync(join(SRC, 'openmoji/data/openmoji.json'), 'utf8'));
const openmojiOf = new Map(openmoji.map((e) => [stripVs(e.emoji), `openmoji/${e.hexcode}`]));

const chosen: Record<string, string> = {};
const report: string[][] = [['concept', 'english', 'picture', 'how']];
for (const c of Object.values(BUILTIN_CONCEPTS)) {
  let key: string | undefined;
  let how = '';
  if (c.id in overrides) {
    key = overrides[c.id] ?? undefined;
    how = key ? 'chosen by hand' : '';
  } else {
    key = mulberryByName.get(norm(c.labels.en));
    how = key ? 'Mulberry, same name' : '';
  }
  if (!key) {
    key = openmojiOf.get(stripVs(c.emoji));
    how = key ? 'OpenMoji drawing of the emoji' : 'emoji (no picture)';
  }
  if (key && !fileOf.has(key)) {
    console.log(`! ${c.id}: ${key} is not in the library`);
    key = undefined;
    how = 'emoji (no picture)';
  }
  if (key) chosen[c.id] = key;
  report.push([c.id, c.labels.en, key ?? c.emoji, how]);
}

mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) unlinkSync(join(out, f));
const keys = [...new Set(Object.values(chosen))].sort();
const fileName = (key: string) => key.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_|_$/g, '') + '.webp';
for (const key of keys) {
  const [lib] = key.split('/');
  await sharp(join(SRC, lib, fileOf.get(key)!), { density: 400 })
    .resize(SIZE, SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .webp({ quality: 82, alphaQuality: 90 })
    .toFile(join(out, fileName(key)));
}
writeFileSync(
  join(root, 'src/data/symbolMap.ts'),
  `// GENERATED by scripts/build-default-symbols.ts — do not edit by hand.\n// Pictures of the built-in vocabulary: Mulberry Symbols (CC BY-SA 4.0) and OpenMoji (CC BY-SA 4.0), unmodified (resized).\n/* eslint-disable */\n\n/** Picture of each built-in word: a pictogram key (library/name). */\nexport const SYMBOL_DEFAULTS: Record<string, string> = ${JSON.stringify(chosen, null, 2)};\n\nexport const SYMBOL_IMAGES: Record<string, number> = {\n${keys.map((k) => `  ${JSON.stringify(k)}: require('../../assets/symbols/${fileName(k)}'),`).join('\n')}\n};\n`,
);
writeFileSync(join(root, 'pictograms/database/defaults.csv'), report.map((r) => r.map((v) => (/[",]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v)).join(',')).join('\n') + '\n');
const count = (h: string) => report.filter((r) => r[3] === h).length;
console.log(`${Object.keys(chosen).length} of ${report.length - 1} words have a picture (${keys.length} files): Mulberry same name ${count('Mulberry, same name')}, by hand ${count('chosen by hand')}, OpenMoji ${count('OpenMoji drawing of the emoji')}, emoji only ${count('emoji (no picture)')}`);

// Contact sheet to check the choices by eye.
if (process.env.SHEET) {
  const cols = 16;
  const cell = 96;
  const list = report.slice(1).filter((r) => chosen[r[0]]);
  const comp = await Promise.all(
    list.map(async (r, i) => ({
      input: await sharp(join(out, fileName(chosen[r[0]]))).resize(cell - 8, cell - 22, { fit: 'contain', background: '#ffffff' }).flatten({ background: '#ffffff' }).png().toBuffer(),
      left: (i % cols) * cell + 4,
      top: Math.floor(i / cols) * cell + 2,
    })),
  );
  const labels = list
    .map((r, i) => `<text x="${(i % cols) * cell + cell / 2}" y="${Math.floor(i / cols) * cell + cell - 6}" font-size="11" text-anchor="middle" font-family="sans-serif">${r[0].slice(0, 14)}</text>`)
    .join('');
  const h = Math.ceil(list.length / cols) * cell;
  await sharp({ create: { width: cols * cell, height: h, channels: 4, background: '#ffffff' } })
    .composite([...comp, { input: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${cols * cell}" height="${h}">${labels}</svg>`), left: 0, top: 0 }])
    .png()
    .toFile(process.env.SHEET);
}
