const DICTS: Record<UiLang, Dict> = { fr, en, ar };
export type AccountStrings = Dict;
export const accountStrings = (l: UiLang): Dict => DICTS[l];

/** A server error code → a sentence for the person. */
export function errorText(s: Dict, e: unknown): string {
  const code = (e as { code?: string })?.code;
  return (code && s.errors[code]) || s.errors.generic;
}
